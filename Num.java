package eaxm;

public class Num {
    public static void main(String[] args) {

        for (int i = 1; i <= 10; i++) {

            if (i % 2 == 0) {
                System.out.println(i + " : 짝수입니다");
            } else {
                System.out.println(i + " : 홀수입니다");
            }

        }

    }
}